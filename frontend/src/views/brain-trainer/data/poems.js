/**
 * Получить случайный стих
 * @returns {Object} случайный стих
 */
export const getRandomPoem = () => {
  const randomIndex = Math.floor(Math.random() * poems.length)
  return poems[randomIndex]
}

/**
 * Получить стих по ID
 * @param {number} id - ID стиха
 * @returns {Object} стих
 */
export const getPoemById = (id) => {
  return poems.find(poem => poem.id === id)
}
