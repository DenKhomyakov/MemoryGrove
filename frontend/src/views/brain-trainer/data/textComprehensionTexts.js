/**
 * Получить случайный текст
 * @returns {Object} случайный текст
 */
export const getRandomText = () => {
  const randomIndex = Math.floor(Math.random() * comprehensionTexts.length)
  return comprehensionTexts[randomIndex]
}

/**
 * Получить текст по ID
 * @param {number} id - ID текста
 * @returns {Object} текст
 */
export const getTextById = (id) => {
  return comprehensionTexts.find(text => text.id === id)
}
