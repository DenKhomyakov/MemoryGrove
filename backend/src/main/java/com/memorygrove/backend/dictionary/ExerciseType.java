package com.memorygrove.backend.dictionary;

/**
 * Перечисление типов упражнений для тренировки памяти
 * <p>
 * Содержит все доступные типы упражнений в системе:
 * <ul>
 *   <li>ARITHMETIC - Арифметическая цепочка</li>
 *   <li>TEXT_COMPREHENSION - Понимание текста (вопросы по рассказу)</li>
 *   <li>POEM - Заучивание стихов</li>
 *   <li>ASSOCIATION - Ассоциации</li>
 *   <li>SEQUENCE - Продолжи ряд</li>
 *   <li>REVERSE_WORD - Слово наоборот</li>
 *   <li>ODD_ONE_OUT - Что лишнее?</li>
 *   <li>SCHULTE_TABLE - Таблица Шульте</li>
 * </ul>
 * </p>
 */
public enum ExerciseType {

    /**
     * Арифметическая цепочка
     * Пользователь решает последовательность примеров: 2 + 3 - 1 + 5
     */
    ARITHMETIC,

    /**
     * Понимание текста
     * Пользователь читает короткий рассказ и отвечает на вопросы
     */
    TEXT_COMPREHENSION,

    /**
     * Заучивание стихов
     * Пользователь запоминает четверостишие и воспроизводит его по памяти
     */
    POEM,

    /**
     * Ассоциации
     * К слову нужно подобрать ассоциацию из предложенных вариантов
     */
    ASSOCIATION,

    /**
     * Продолжи ряд
     * Нужно определить закономерность и продолжить последовательность
     */
    SEQUENCE,

    /**
     * Слово наоборот
     * Нужно написать слово задом наперёд
     */
    REVERSE_WORD,

    /**
     * Что лишнее?
     * Из набора слов нужно выбрать лишнее
     */
    ODD_ONE_OUT,

    /**
     * Таблица Шульте (упрощённая)
     * Нужно нажимать на цифры по порядку
     */
    SCHULTE_TABLE
}
